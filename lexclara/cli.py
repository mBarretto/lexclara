"""Command line: ``lexclara serve`` and ``lexclara demo``."""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

from . import agents, llm, ops
from .model import Document
from .parser import parse

ROOT = Path(__file__).resolve().parent.parent
EXAMPLES = ROOT / "examples"

# The demo runs the agents on the blocks that show each capability best.
DEMO = [
    ("pl_linguagem_simples.txt", "ato_normativo", ["Art. 3º", "Art. 4º"]),
    ("despacho_exigencia.txt", "comunicacao", [agents.DOC_UID]),  # a communication is one unit
]


def _pick(doc: Document, key: str) -> str:
    if key == agents.DOC_UID:
        return key
    return next(a.uid for a in doc.articles() if a.label == key)


def demo(out: Path) -> None:
    lines = ["# LexClara demo run", "",
             f"Model: `{llm.MODEL}`. Generated by `lexclara demo`; every model response is recorded "
             "in `examples/cache/`, so `lexclara demo --replay` reproduces this file without an API key.", ""]

    for filename, doc_type, keys in DEMO:
        doc = parse((EXAMPLES / filename).read_text(encoding="utf-8"), doc_type)
        lines += [f"## `{filename}`", ""]

        findings = ops.check_all(doc)
        lines += ["### Deterministic checks (no model)", "", "| Block | Severity | Rule | Finding |", "|---|---|---|---|"]
        for f in findings:
            b = doc.find(f.block_uid)
            lines.append(f"| {b.label or b.kind} | {f.severity} | {f.rule} | {f.message} |")
        lines.append("")

        if doc_type == "ato_normativo":
            lines += _renumber_story(filename, doc_type)

        for key in keys:
            uid = _pick(doc, key)
            unit = agents.unit_of(doc, uid)
            name = unit.label or "Whole communication"
            print(f"[{filename}] {name}: técnica…", file=sys.stderr)
            tec = agents.tecnica(doc, uid)
            print(f"[{filename}] {name}: versão cidadã + fidelidade…", file=sys.stderr)
            ver = agents.versao_cidada_verificada(doc, uid)
            print(f"[{filename}] {name}: teste de compreensão…", file=sys.stderr)
            comp = agents.compreensao(doc, uid, ver.final.versao)
            lines += _unit_report(name, unit.render(), tec, ver, comp)

    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}", file=sys.stderr)


def _renumber_story(filename: str, doc_type: str) -> list[str]:
    doc = parse((EXAMPLES / filename).read_text(encoding="utf-8"), doc_type)
    art2 = doc.articles()[1]
    ops.insert_after(doc, art2.uid, text="(novo artigo inserido durante a tramitação)")
    stale = [f for f in ops.check_all(doc) if f.agent == "remissoes" and f.fix]
    out = ["### Cross-references after an amendment", "",
           "A new article is inserted after Art. 2º, so every later article is renumbered. "
           "References are bound to blocks, not to numbers, so the editor knows which ones now point "
           "to the wrong place and proposes the corrected text:", ""]
    for f in stale:
        out.append(f"- {doc.find(f.block_uid).label}: “{f.fix.old}” → “{f.fix.new}”")
    return out + [""]


def _unit_report(name, official, tec, ver, comp) -> list[str]:
    out = [f"### {name}", "", "Official text:", "", "```", official, "```", "",
           "**Drafting review (LC 95/1998, art. 11)**", ""]
    for p in tec.problemas:
        out.append(f"- *{p.regra}* — “{p.trecho}”: {p.problema} **Suggestion:** {p.sugestao}")
    if tec.redacao_sugerida:
        out += ["", "Proposed text:", "", "```", tec.redacao_sugerida, "```"]
    out += ["", "**Plain-language version, verified for legal fidelity**", ""]
    for i, rd in enumerate(ver.rodadas, start=1):
        v = rd.verificacao
        changed = [a for a in v.atomos if a.status != "preservado"]
        out.append(f"- Round {i}: verdict **{v.veredito}** — {len(v.atomos)} normative propositions, "
                   f"{len(changed)} altered or omitted, {len(v.acrescimos)} unsupported additions.")
        for a in changed:
            out.append(f"  - {a.status}: {a.tipo} ({a.dispositivo}) — {a.enunciado}. {a.comentario}")
        for x in v.acrescimos:
            out.append(f"  - addition: {x}")
    out += ["", "Final version:", "", "> " + agents.render_cidada(ver.final.versao).replace("\n", "\n> "), "",
            "**Comprehension test with simulated readers**", "",
            "| Reader | Official text | Plain version |", "|---|---|---|"]
    by: dict[str, dict] = {}
    for r in comp.resultados:
        by.setdefault(r.leitor, {})[r.versao] = r
    for reader, v in by.items():
        cell = lambda x: f"{x.acertos}/{x.total}" + (f" ({x.nao_sei} não sei)" if x.nao_sei else "") if x else "–"
        out.append(f"| {reader} | {cell(v.get('oficial'))} | {cell(v.get('cidada'))} |")
    out += ["", "Questions (written from the official text):", ""]
    for i, p in enumerate(comp.questionario.perguntas, start=1):
        out.append(f"{i}. {p.pergunta} — *{p.alternativas[p.correta]}* ({p.dispositivo})")
    return out + [""]


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="lexclara")
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("serve", help="run the web editor")
    s.add_argument("--port", type=int, default=int(os.environ.get("PORT", 8000)))
    s.add_argument("--replay", action="store_true", help="use only recorded model responses")
    d = sub.add_parser("demo", help="run the agents on the examples and write a report")
    g = d.add_mutually_exclusive_group()
    g.add_argument("--replay", action="store_true", help="use only recorded responses (no API key needed)")
    g.add_argument("--live", action="store_true", help="call the API and re-record every response")
    d.add_argument("--out", type=Path, default=EXAMPLES / "demo_report.md")
    c = sub.add_parser("check", help="run the deterministic checks on a text file")
    c.add_argument("file", type=Path)
    c.add_argument("--comunicacao", action="store_true")
    args = ap.parse_args(argv)

    if getattr(args, "replay", False):
        llm.MODE = "replay"
    if getattr(args, "live", False):
        llm.MODE = "live"

    if args.cmd == "serve":
        import uvicorn
        uvicorn.run("lexclara.server:app", host="127.0.0.1", port=args.port)
    elif args.cmd == "demo":
        demo(args.out)
    elif args.cmd == "check":
        doc = parse(args.file.read_text(encoding="utf-8"), "comunicacao" if args.comunicacao else "ato_normativo")
        for f in ops.check_all(doc):
            b = doc.find(f.block_uid)
            print(f"{f.severity:5}  {b.label or b.kind:18}  {f.message}  [{f.rule}]")


if __name__ == "__main__":
    main()
